    assert.deepEqual(data.pose_order,["seated","seated_raised","raised"]);
    assert.deepEqual(data.sprites.map(s=>s.pose),data.pose_order.flatMap(p=>Array(6).fill(p)));
    const regions=atlasRegions(data);assert.equal(regions.length,18);
    assert.ok(data.sprites.slice(6,12).every(s=>s.mask_rects.length>=1),"neighbour fragments are explicitly masked");
    for(const region of regions){assert.equal(region.masks.length,3);assert.ok(region.size.x>0 && region.size.y>0);}
    const uniforms=createCrowdUniforms(),texture=new T.Texture(),mesh=createAtlasCrowd(crowdLayout(12,1),uniforms,{texture,metadata:data});
