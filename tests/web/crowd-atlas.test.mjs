    assert.equal(mesh.material.customProgramCacheKey(),"vmi-crowd-pose-blend-6-v3");
    assert.match(shader.vertexShader,/vec3\(1.0-raised,raised-standing,standing\)/);
    assert.equal(shader.uniforms.crowdMasksA.value.length,18);
